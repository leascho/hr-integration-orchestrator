"""Status values for integration runs and steps."""

from enum import StrEnum


class RunStatus(StrEnum):
    RECEIVED = "RECEIVED"
    VALIDATED = "VALIDATED"
    IN_PROGRESS = "IN_PROGRESS"
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"
    RETRYING = "RETRYING"
    MANUAL_REVIEW_REQUIRED = "MANUAL_REVIEW_REQUIRED"


class StepStatus(StrEnum):
    PENDING = "PENDING"
    IN_PROGRESS = "IN_PROGRESS"
    RETRYING = "RETRYING"
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"
    SKIPPED = "SKIPPED"


class StepName(StrEnum):
    MAP_TO_CANONICAL = "MAP_TO_CANONICAL"
    PROVISION_IDENTITY = "PROVISION_IDENTITY"
    CREATE_ONBOARDING_TASK = "CREATE_ONBOARDING_TASK"
    SEND_WELCOME_NOTIFICATION = "SEND_WELCOME_NOTIFICATION"
